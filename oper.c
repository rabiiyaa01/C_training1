#include <stdio.h>
void main ()
{
    int n1 = 34;
    int n2 = 57;
    int sum = n1+n2;
    int sub = n1-n2;
    int pro = n1*n2;
    int quo = n1/n2;
    int rem = n1%n2;
    printf("addition: %d \n",sum);
    printf("subtraction: %d \n",sub);
    printf("multiplication: %d \n",pro);
    printf("division: %d \n",quo);
    printf("remainder: %d \n",rem);
}